[CmdletBinding()]
param(
    [string]$JdkPath = $env:JAVA_HOME,
    [string]$SdkPath = $(if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { $env:ANDROID_SDK_ROOT })
)

$ErrorActionPreference = 'Stop'

if (-not $JdkPath -or -not (Test-Path -LiteralPath (Join-Path $JdkPath 'bin/javac.exe'))) {
    throw 'JDK 21 is required. Supply -JdkPath or set JAVA_HOME to a JDK 21 directory.'
}
if (-not $SdkPath -or -not (Test-Path -LiteralPath $SdkPath -PathType Container)) {
    throw 'Android SDK is required. Supply -SdkPath or set ANDROID_HOME.'
}

$resolvedJdk = (Resolve-Path -LiteralPath $JdkPath).ProviderPath
$resolvedSdk = (Resolve-Path -LiteralPath $SdkPath).ProviderPath
$compilerVersion = & (Join-Path $resolvedJdk 'bin/javac.exe') -version 2>&1
if ($LASTEXITCODE -ne 0 -or "$compilerVersion" -notmatch '^javac 21\.') {
    throw "Expected JDK 21, found: $compilerVersion"
}

foreach ($sdkComponent in @('platforms/android-36/android.jar', 'build-tools/35.0.0/aapt2.exe')) {
    if (-not (Test-Path -LiteralPath (Join-Path $resolvedSdk $sdkComponent))) {
        throw "Missing SDK component: $sdkComponent. Install platforms;android-36 and build-tools;35.0.0 with SDK Manager."
    }
}

$sdkProperty = $resolvedSdk.Replace('\', '/').Replace(':', '\:')
$sdkProperty = [regex]::Replace($sdkProperty, '[^\x20-\x7e]', {
    param($match)
    '\u{0:x4}' -f [int][char]$match.Value
})
$localProperties = Join-Path $PSScriptRoot '../local.properties'
[System.IO.File]::WriteAllText(
    $localProperties,
    "# Local SDK path; generated by scripts/android-env.ps1 and ignored by Git.`nsdk.dir=$sdkProperty`n",
    [System.Text.UTF8Encoding]::new($false)
)

$env:JAVA_HOME = $resolvedJdk
$env:ANDROID_HOME = $resolvedSdk
$jdkBin = Join-Path $resolvedJdk 'bin'
$platformTools = Join-Path $resolvedSdk 'platform-tools'
$remainingPath = ($env:Path -split ';' | Where-Object { $_ -ne $jdkBin -and $_ -ne $platformTools }) -join ';'
$env:Path = "$jdkBin;$platformTools;$remainingPath"

Write-Host "JDK: $resolvedJdk"
Write-Host "SDK: $resolvedSdk"
Write-Host 'Current PowerShell environment and local.properties are ready. Run .\gradlew.bat :app:lintDebug :app:assembleDebug'
